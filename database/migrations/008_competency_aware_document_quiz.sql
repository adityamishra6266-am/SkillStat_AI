-- ============================================================
-- SkillStat AI — Migration 008: Competency-aware document quizzes
--                              + transparent assessment provenance
--                              (final integration)
-- ============================================================
-- SAFE / ADDITIVE MIGRATION
--   Nothing is dropped, renamed or narrowed; every new column is
--   nullable so all existing rows keep working unchanged.
--
--   quiz_questions
--     source_type        where the question came from:
--                        'bank'       curated diagnostic_questions bank
--                        'llm'        generated by a configured LLM
--                        'extractive' deterministic generator built from
--                                     the uploaded document's own sentences
--     mapping_confidence 0.00-1.00 confidence that competency_id is right
--                        (only meaningful when competency_id IS NOT NULL)
--     mapping_method     'curated' | 'llm' | 'keyword'
--     mapping_reason     short human-readable reason for the mapping
--     (competency_id already exists from migration 002. It stays NULL
--      when no reliable competency could be determined — a mapping is
--      never fabricated.)
--
--   quizzes.generation_mode   'curated_bank' | 'ai_assisted' |
--                             'document_llm' | 'document_extractive'
--   quiz_attempts.adaptive_update_json
--                             what the adaptive pipeline actually did
--                             after this attempt (competency updated /
--                             gaps recalculated / recommendations
--                             refreshed / path updated), so the Result
--                             page can show it truthfully after a reload.
--
-- Run AFTER 002-007:
--   mysql -u <user> -p skillstat_ai < database/migrations/008_competency_aware_document_quiz.sql
-- ============================================================

USE skillstat_ai;

ALTER TABLE quiz_questions
  ADD COLUMN source_type ENUM('bank', 'llm', 'extractive') NULL AFTER question_type,
  ADD COLUMN mapping_confidence DECIMAL(4,2) NULL AFTER source_type,
  ADD COLUMN mapping_method VARCHAR(20) NULL AFTER mapping_confidence,
  ADD COLUMN mapping_reason VARCHAR(500) NULL AFTER mapping_method;

ALTER TABLE quizzes
  ADD COLUMN generation_mode VARCHAR(30) NULL AFTER quiz_type;

ALTER TABLE quiz_attempts
  ADD COLUMN adaptive_update_json JSON NULL AFTER answers_json;
